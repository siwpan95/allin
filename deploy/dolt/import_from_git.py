#!/usr/bin/env python3
"""Git 结构化真身 -> Dolt 单向导入器（B 期）。

纪律：
  * Git 内 `facts/facts.json` 是唯一写入权威；Dolt 是可重建派生物，绝不反向写回 Git；
  * **SQL COMMIT 不产生 dolt commit** —— 导入末尾必须显式 `CALL DOLT_COMMIT(...)`，
    否则 `AS OF` / `dolt_diff_*` 时间轴断裂（官方硬约束）；
  * 每次 commit message 与 `fact_version` 都写 `source_git_sha`，作为跨
    Git / Dolt / NetBox / GraphRAG 的统一溯源键；
  * 默认 dry-run，只有 `--apply` 且检测到 `dolt` 二进制才真写（ADR-0003 写入需显式确认）；
  * 派生库全量重建是允许的（Git 才是真身），但 `fact` 行在 Git 侧仍遵守 SCD-2 append-only。

零第三方依赖。退出码：0 干净 / 1 有 finding / 2 用法错 / 3 环境错。
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")

EXIT_OK, EXIT_BLOCKING, EXIT_USAGE, EXIT_ENV = 0, 1, 2, 3
ROOT = Path(__file__).resolve().parents[2]
DEFAULT_DATA = ROOT / "facts" / "facts.json"
DEFAULT_SCHEMA = ROOT / "deploy" / "dolt" / "schema.sql"
DEFAULT_WORKSPACE = ROOT / "facts" / "dolt-workspace"
DEFAULT_STATE = ROOT / "deploy" / "dolt" / "state" / "last_import.json"


def git_commit_time(root: Path) -> str:
    """Git 提交时间，确定性值；避免用当前时间让同一真身的两次导入产生不同 SQL。"""
    try:
        r = subprocess.run(["git", "-C", str(root), "show", "-s", "--format=%cI", "HEAD"],
                           capture_output=True, text=True, encoding="utf-8", timeout=10)
        s = r.stdout.strip()
        return s[:19].replace("T", " ") if r.returncode == 0 and s else "1970-01-01 00:00:00"
    except (OSError, subprocess.SubprocessError):
        return "1970-01-01 00:00:00"


def q(v) -> str:
    """MySQL 字面量；不接收任意代码，只接受 JSON 基本类型。"""
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "1" if v else "0"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


def git_sha(root: Path) -> str:
    try:
        r = subprocess.run(["git", "-C", str(root), "rev-parse", "--short", "HEAD"],
                           capture_output=True, text=True, encoding="utf-8", timeout=10)
        return r.stdout.strip() if r.returncode == 0 and r.stdout.strip() else "UNKNOWN"
    except (OSError, subprocess.SubprocessError):
        return "UNKNOWN"


SOURCE_KEYS = {
    "machine": "machines", "volume": "volumes", "runtime": "runtimes",
    "repo_checkout": "repos", "service_port": "ports", "service": "services",
    "fact": "facts", "doc_ref": "doc_refs", "observation_run": "observation_runs",
}


def insert(table: str, cols: list[str], row: dict, pk: str) -> str:
    """纯 INSERT。幂等由「每轮全量重建派生库」保证，不用 ON DUPLICATE KEY UPDATE
    —— 后者会消耗 AUTO_INCREMENT，让表 schema 的计数器变化，Dolt 据此产生空 commit。"""
    vals = ", ".join(q(row.get(c)) for c in cols)
    return f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({vals});"


def build_import_sql(doc: dict, sha: str, run_id: str, ingested_at: str) -> tuple[str, dict]:
    """全量幂等 SQL；重复导入不产生新行（dolt diff 为空时 DOLT_COMMIT 为 no-op）。"""
    out = [
        "-- generated by deploy/dolt/import_from_git.py; do not edit by hand",
        f"-- source_git_sha={sha} ingest_run_id={run_id}",
        "-- 全量重建派生库（Git 才是真身）：逆向清空尊重外键，重置自增保证 SQL 确定。",
    ]
    tables = [
        ("machine", ["machine_id", "hostname", "os_caption", "os_build", "cpu", "ram_gb",
                     "status", "visibility", "evidence_ref", "observed_at", "valid_from", "valid_to"], "machine_id"),
        ("volume", ["machine_id", "letter", "label", "fs", "size_gb", "free_gb", "role",
                    "observed_at", "valid_from", "evidence_ref"], "volume_id"),
        ("runtime", ["machine_id", "tool", "exe_path", "version", "flags_json", "is_primary",
                     "observed_at", "evidence_ref"], "runtime_id"),
        ("repo_checkout", ["machine_id", "repo_id", "local_path", "has_git", "has_origin", "state",
                           "observed_at", "evidence_ref"], "checkout_id"),
        ("service", ["service_id", "name", "kind", "lifecycle", "owner_ref", "depends_on_json",
                     "visibility", "observed_at", "evidence_ref"], "service_id"),
        ("service_port", ["port", "service", "owner_ref", "segment", "status", "machine_id",
                          "observed_at", "evidence_ref"], "port"),
        ("doc_ref", ["doc_id", "path", "section", "kind", "is_generated", "visibility"], "doc_id"),
        ("observation_run", ["run_id", "machine_id", "ts", "command", "raw_hash",
                             "adjudicated_by", "evidence_ref"], "run_id"),
        ("fact", ["fact_id", "subject", "attribute", "value_text", "value_number", "unit", "scope",
                  "machine_id", "status", "valid_from", "valid_to", "observed_at", "observed_by",
                  "evidence_ref", "source_file", "source_line", "supersedes", "visibility"], "fact_id"),
    ]
    # 字段名映射：JSON 真身用 exe_path / state / generated 等，SQL 列名略有差异
    aliases = {
        "runtime": {"path": "exe_path"},
        "repo_checkout": {"checkout_state": "state"},
        "service": {"owner": "owner_ref"},
        "service_port": {"owner": "owner_ref"},
        "doc_ref": {"generated": "is_generated"},
        "fact": {"value": "value_text"},
    }
    counts = {}
    # 逆序清空（volume / runtime / repo_checkout 有外键指向 machine），再重置自增计数器。
    for table, _, _ in reversed(tables):
        out.append(f"DELETE FROM {table};")
    out.append("DELETE FROM fact_version;")
    for t in ("volume", "runtime", "repo_checkout", "fact_version"):
        out.append(f"ALTER TABLE {t} AUTO_INCREMENT = 1;")
    for table, cols, pk in tables:
        rows = doc.get(SOURCE_KEYS[table], [])
        counts[table] = len(rows)
        for raw in rows:
            row = dict(raw)
            if table == "observation_run" and isinstance(row.get("ts"), str):
                # JSON 里是 ISO 8601 带时区，MySQL DATETIME 只接受无时区形式
                row["ts"] = row["ts"][:19].replace("T", " ")
            if table == "volume" and not row.get("valid_from"):
                # volume 表 valid_from NOT NULL；真身只给了 observed_at 时以观测日兜底
                row["valid_from"] = row.get("observed_at")
            for src, dst in aliases.get(table, {}).items():
                if src in row:
                    row[dst] = row.pop(src)
            if "flags_json" in cols and isinstance(row.get("flags_json"), list):
                row["flags_json"] = json.dumps(row["flags_json"], ensure_ascii=False)
            if "depends_on_json" in cols and isinstance(row.get("depends_on_json"), list):
                row["depends_on_json"] = json.dumps(row["depends_on_json"], ensure_ascii=False)
            if "value_text" in cols and "value_text" in row and not isinstance(row["value_text"], (str, type(None))):
                row["value_text"] = str(row["value_text"])
            out.append(insert(table, cols, row, pk))
    for f in doc.get("facts", []):
        out.append(insert("fact_version",
                          ["table_name", "row_pk", "source_path", "source_git_sha",
                           "ingest_run_id", "ingested_at"],
                          {"table_name": "fact", "row_pk": f["fact_id"],
                           "source_path": "facts/facts.json", "source_git_sha": sha,
                           "ingest_run_id": run_id, "ingested_at": ingested_at},
                          "fact_version_id"))
    counts["fact_version"] = len(doc.get("facts", []))
    # 关键：SQL COMMIT ≠ dolt commit，必须显式调用，且 commit message 带 source_git_sha
    out.append(f"CALL DOLT_COMMIT('-Am', {q('facts: import git@' + sha)}, "
               f"'--author', 'allin-bot <allin@example.invalid>');")
    return "\n".join(out) + "\n", counts


def run_cmd(cmd: list[str], cwd: Path, stdin_file: Path | None = None) -> tuple[int, str]:
    try:
        if stdin_file:
            with stdin_file.open("r", encoding="utf-8") as fh:
                r = subprocess.run(cmd, cwd=str(cwd), stdin=fh, capture_output=True,
                                   text=True, encoding="utf-8", errors="replace", timeout=180)
        else:
            r = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True,
                               encoding="utf-8", errors="replace", timeout=180)
        return r.returncode, (r.stdout or "") + (r.stderr or "")
    except (OSError, subprocess.SubprocessError) as e:
        return 3, str(e)


def apply(workspace: Path, schema: Path, sql_text: str, sha: str, run_id: str) -> dict:
    if shutil.which("dolt") is None:
        return {"status": "ENV_ERROR", "reason": "dolt 二进制不在 PATH；本次未写任何 Dolt 数据"}
    workspace.mkdir(parents=True, exist_ok=True)
    if not (workspace / ".dolt").is_dir():
        rc, out = run_cmd(["dolt", "init", "--name", "allin-bot",
                           "--email", "allin@example.invalid"], workspace)
        if rc != 0:
            return {"status": "FAIL", "stage": "dolt init", "exit": rc, "output": out[-500:]}
    sql_path = workspace / "import.sql"
    sql_path.write_text(sql_text, encoding="utf-8")
    stages = {}
    for label, path in (("schema", schema), ("import", sql_path)):
        rc, out = run_cmd(["dolt", "sql"], workspace, stdin_file=path)
        stages[label] = {"exit": rc, "output": out[-300:]}
        # "nothing to commit" 是幂等重导的正常结果，不是失败
        if rc != 0 and "nothing to commit" not in out.lower() and "no changes" not in out.lower():
            return {"status": "FAIL", "stage": label, "stages": stages}
    rc, out = run_cmd(["dolt", "log", "--oneline", "-n", "3"], workspace)
    return {"status": "OK", "stages": stages, "dolt_log_tail": out[-400:],
            "source_git_sha": sha, "ingest_run_id": run_id, "workspace": str(workspace)}


def selftest() -> int:
    doc = json.loads(DEFAULT_DATA.read_text(encoding="utf-8"))
    sha, run_id, ts = "abc1234", "RUN-SELFTEST", "2026-11-09 07:00:00"
    sql1, counts1 = build_import_sql(doc, sha, run_id, ts)
    sql2, counts2 = build_import_sql(doc, sha, run_id, ts)
    idempotent = sql1 == sql2
    has_commit = "CALL DOLT_COMMIT" in sql1 and f"git@{sha}" in sql1
    has_provenance = "fact_version" in sql1 and sha in sql1
    quote_ok = (q(None) == "NULL" and q(True) == "1" and q(138) == "138"
                and q("a'b") == "'a''b'")
    ok = idempotent and has_commit and has_provenance and quote_ok
    print(json.dumps({"idempotent": idempotent, "dolt_commit_explicit": has_commit,
                      "source_git_sha_in_sql": has_provenance, "quoting": quote_ok,
                      "row_counts": counts1, "dolt_available": shutil.which("dolt") is not None,
                      "selftest": "PASS" if ok else "FAIL"}, ensure_ascii=False))
    return EXIT_OK if ok else EXIT_BLOCKING


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="facts.json -> Dolt 单向幂等导入")
    ap.add_argument("--data", type=Path, default=DEFAULT_DATA)
    ap.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA)
    ap.add_argument("--workspace", type=Path, default=DEFAULT_WORKSPACE)
    ap.add_argument("--state", type=Path, default=DEFAULT_STATE)
    ap.add_argument("--apply", action="store_true", help="真正写 Dolt（需 dolt 在 PATH）")
    ap.add_argument("--verify", action="store_true", help="读 dolt log 与 AS OF 验证")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if a.verify:
        if shutil.which("dolt") is None or not (a.workspace / ".dolt").is_dir():
            print("ENV ERROR: dolt 不可用或工作区未初始化（如实 SKIP，不计为通过）")
            return EXIT_ENV
        for label, cmd in (("log", ["dolt", "log", "--oneline", "-n", "5"]),
                           ("asof_head", ["dolt", "sql", "-q",
                                          "SELECT COUNT(*) AS facts_asof_head FROM fact AS OF 'HEAD'"]),
                           ("asof_prev", ["dolt", "sql", "-q",
                                          "SELECT fact_id, value_text FROM fact AS OF 'HEAD~1' "
                                          "WHERE subject='global' AND attribute='gitee_remote_repo_count'"]),
                           ("diff_rows", ["dolt", "sql", "-q",
                                          "SELECT COUNT(*) AS diff_rows FROM dolt_diff_fact "
                                          "WHERE to_commit = HASHOF('HEAD')"])):
            rc, out = run_cmd(cmd, a.workspace)
            print(f"VERIFY {label} exit={rc}\n{out[-600:]}")
        return EXIT_OK
    doc = json.loads(a.data.read_text(encoding="utf-8"))
    sha = git_sha(ROOT)
    run_id = f"git-{sha}"          # 确定性：同一 Git 提交重复导入生成完全相同的 SQL
    ts = git_commit_time(ROOT)     # 确定性：不用当前时间
    sql_text, counts = build_import_sql(doc, sha, run_id, ts)
    print(json.dumps({"mode": "apply" if a.apply else "dry-run", "source_git_sha": sha,
                      "ingest_run_id": run_id, "row_counts": counts,
                      "sql_sha256": hashlib.sha256(sql_text.encode("utf-8")).hexdigest()[:16]},
                     ensure_ascii=False))
    if not a.apply:
        print("DRY-RUN: 未写 Dolt。加 --apply 才生效（写入需显式确认）。")
        return EXIT_OK
    result = apply(a.workspace, a.schema, sql_text, sha, run_id)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    if result.get("status") == "OK":
        a.state.parent.mkdir(parents=True, exist_ok=True)
        a.state.write_text(json.dumps({"source_git_sha": sha, "ingest_run_id": run_id,
                                       "ingested_at": ts, "workspace": str(a.workspace)},
                                      ensure_ascii=False, indent=2), encoding="utf-8")
    return EXIT_OK if result.get("status") == "OK" else EXIT_ENV


if __name__ == "__main__":
    raise SystemExit(main())
