"""refresh-gov-block.py -- keep every copy of the governance segment identical.

CANONICAL SOURCE
    preset/allin/allin.patch.yml -- the `<!-- GOVERNANCE:BEGIN` ... `<!-- GOVERNANCE:END`
    segment (hereafter "the governance segment"). This is the only text a human edits.

DERIVED COPIES
    1. preset/allin/agent.cordis.yml -- archived 0.1.6 directory-form preset (6-space
       indent, CRLF). Nothing loads it, which is how it ran a 2026-09 snapshot for a
       month without anyone noticing.
    2. <DSH_HOME>/profiles/web/cordis.patch.yml -- the *mounted* profile layer (16-space
       indent). This one reaches live sessions; on 2026-10-29 it was still telling new
       agents "15 gates" while the repository said 19.
    3. preset/allin/bundle/cordis.patch.yml -- the npm bundle copy. It is a whole-file
       copy regenerated by `make-bundle.ps1`, so this tool only *checks* it (one writer
       per file).

WHY A TOOL
    Three copies plus hand edits is drift no gate inside the repository can see: copy 2
    lives outside the repo entirely. Prose cannot keep them in step; an idempotent writer
    can, and `--check` turns "is the deployment current?" into an exit code.

USAGE
    python preset/allin/refresh-gov-block.py --check
    python preset/allin/refresh-gov-block.py --write
    python preset/allin/refresh-gov-block.py --write --targets agent
    python preset/allin/refresh-gov-block.py --check --profile-path <path>

EXIT CODES
    0  every copy is fresh (or was just refreshed)
    2  usage error, or the canonical governance segment is not a well-formed pair
    3  --check only: at least one derived copy is stale (mirrors `make-bundle.ps1 -Check`)
"""
from __future__ import annotations

import argparse
import hashlib
import os
import sys
from dataclasses import dataclass
from pathlib import Path

CANONICAL = Path("preset") / "allin" / "allin.patch.yml"
AGENT_COPY = Path("preset") / "allin" / "agent.cordis.yml"
BUNDLE_COPY = Path("preset") / "allin" / "bundle" / "cordis.patch.yml"
PROFILE_COPY = Path("profiles") / "web" / "cordis.patch.yml"

MARKER_BEGIN = "<!-- GOVERNANCE:BEGIN"
MARKER_END = "<!-- GOVERNANCE:END"

EXIT_OK = 0
EXIT_USAGE = 2
EXIT_STALE = 3


@dataclass
class Reading:
    """One file as it is on disk, plus the two conventions a rewrite must preserve."""

    text: str
    bom: bool
    eol: str


def read(path: Path) -> Reading:
    """Read UTF-8 text and remember whether it carried a BOM and which EOL it used."""
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    text = raw.decode("utf-8-sig")
    eol = "\r\n" if "\r\n" in text else "\n"
    return Reading(text=text, bom=bom, eol=eol)


def write(path: Path, reading: Reading, text: str) -> None:
    """Write back with the original BOM and EOL convention: no incidental diff noise."""
    body = text.replace("\r\n", "\n").replace("\n", reading.eol)
    path.write_bytes((b"\xef\xbb\xbf" if reading.bom else b"") + body.encode("utf-8"))


def marker_indexes(lines: list[str]) -> tuple[int, int] | None:
    """Line indexes of the marked segment, anchored on the marker *lines*.

    A prose comment above a preset legitimately names the markers ("GOVERNANCE:BEGIN/END
    段"), so a substring search would return the comment block instead of the segment.
    """
    starts = [i for i, line in enumerate(lines) if line.strip().startswith(MARKER_BEGIN)]
    stops = [i for i, line in enumerate(lines) if line.strip().startswith(MARKER_END)]
    if len(starts) != 1 or len(stops) != 1 or stops[0] < starts[0]:
        return None
    return starts[0], stops[0]


def normalize(lines: list[str]) -> str:
    """Comparable form: no common indent, no trailing blanks, LF newlines."""
    trimmed = [line.rstrip() for line in lines]
    indents = [len(line) - len(line.lstrip()) for line in trimmed if line.strip()]
    base = min(indents) if indents else 0
    return "\n".join(line[base:] if line.strip() else "" for line in trimmed).strip("\n")


def reindent(lines: list[str], indent: int) -> list[str]:
    return [(" " * indent + line) if line.strip() else "" for line in normalize(lines).split("\n")]


def detect_indent(lines: list[str]) -> int:
    indents = [len(line) - len(line.lstrip()) for line in lines if line.strip()]
    return min(indents) if indents else 0


def default_profile() -> Path | None:
    """The mounted profile layer for this machine, or None when there is none."""
    home = os.environ.get("DSH_HOME")
    base = Path(home) if home else Path.home() / ".dsh"
    candidate = base / PROFILE_COPY
    return candidate if candidate.is_file() else None


def first_difference(current: str, canonical: str) -> str:
    """A one-line pointer to where a stale copy diverges: usable, not just "different"."""
    left = current.split("\n")
    right = canonical.split("\n")
    for number, (a, b) in enumerate(zip(left, right), start=1):
        if a != b:
            column = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
            low = max(0, column - 16)
            return (f"first difference at segment line {number}, column {column + 1}: "
                    f"{a[low:column + 20]!r} != {b[low:column + 20]!r}")
    return f"line count {len(left)} != canonical {len(right)}"


def refresh_segment(path: Path, canonical_lines: list[str]) -> tuple[int, int]:
    """Rewrite the marked segment in ``path`` from the canonical text; return (old, new) lines."""
    reading = read(path)
    lines = reading.text.splitlines()
    indexes = marker_indexes(lines)
    if indexes is None:
        raise SystemExit(f"{path}: {MARKER_BEGIN}/{MARKER_END} is not a well-formed pair")
    start, stop = indexes
    new_lines = reindent(canonical_lines, detect_indent(lines[start : stop + 1]))
    rebuilt = "\n".join(lines[:start] + new_lines + lines[stop + 1 :])
    write(path, reading, rebuilt + reading.eol)
    return stop - start + 1, len(new_lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="keep every governance-segment copy identical to preset/allin/allin.patch.yml")
    parser.add_argument("--check", action="store_true", help="compare only; exit 3 when a copy is stale")
    parser.add_argument("--write", action="store_true", help="rewrite the stale copies (agent, profile)")
    parser.add_argument("--targets", default="agent,profile,bundle",
                        help="comma list drawn from agent,profile,bundle (default: all)")
    parser.add_argument("--profile-path", default="",
                        help="mounted profile patch (default: $DSH_HOME/profiles/web/cordis.patch.yml)")
    args = parser.parse_args(argv)
    if args.check == args.write:
        print("pass exactly one of --check / --write")
        return EXIT_USAGE

    repo = Path(__file__).resolve().parents[2]
    canonical_path = repo / CANONICAL
    if not canonical_path.is_file():
        print(f"canonical source missing: {canonical_path}")
        return EXIT_USAGE
    canonical_lines = read(canonical_path).text.splitlines()
    canonical_indexes = marker_indexes(canonical_lines)
    if canonical_indexes is None:
        print(f"{canonical_path}: {MARKER_BEGIN}/{MARKER_END} is not a well-formed pair")
        return EXIT_USAGE
    canonical_slice = canonical_lines[canonical_indexes[0] : canonical_indexes[1] + 1]
    canonical_norm = normalize(canonical_slice)
    print(f"canonical: {len(canonical_slice)} lines / {len(canonical_norm)} chars "
          f"from {CANONICAL.as_posix()}")

    wanted = [item.strip() for item in args.targets.split(",") if item.strip()]
    unknown = [item for item in wanted if item not in {"agent", "profile", "bundle"}]
    if unknown:
        print(f"unknown target(s): {', '.join(unknown)}")
        return EXIT_USAGE

    stale: list[str] = []
    for target in wanted:
        if target == "bundle":
            bundle_path = repo / BUNDLE_COPY
            if not bundle_path.is_file():
                print("bundle : missing -> run make-bundle.ps1")
                stale.append("bundle")
            elif hashlib.sha256(canonical_path.read_bytes()).hexdigest() == \
                    hashlib.sha256(bundle_path.read_bytes()).hexdigest():
                print("bundle : fresh (byte-identical to the canonical patch)")
            else:
                print("bundle : STALE -> run make-bundle.ps1 (whole-file copy, not written by this tool)")
                stale.append("bundle")
            continue

        if target == "agent":
            path = repo / AGENT_COPY
        else:
            path = Path(args.profile_path) if args.profile_path else default_profile()
            if path is None:
                print("profile: no mounted profile layer on this machine -- skipped (not a pass)")
                continue
            if not path.is_file():
                print(f"profile: {path} does not exist -- skipped (not a pass)")
                continue

        reading = read(path)
        indexes = marker_indexes(reading.text.splitlines())
        if indexes is None:
            print(f"{target}: {MARKER_BEGIN}/{MARKER_END} is not a well-formed pair; cannot judge")
            stale.append(target)
            continue
        current = normalize(reading.text.splitlines()[indexes[0] : indexes[1] + 1])
        if current == canonical_norm:
            print(f"{target}: fresh {indexes[1] - indexes[0] + 1} lines / {len(current)} chars")
            continue
        if not args.write:
            print(f"{target}: STALE ({first_difference(current, canonical_norm)}) -> {path}")
            stale.append(target)
            continue
        old_count, new_count = refresh_segment(path, canonical_slice)
        print(f"{target}: refreshed ({old_count} -> {new_count} lines) -> {path}")

    if args.check and stale:
        print(f"stale copy/copies: {', '.join(stale)}")
        return EXIT_STALE
    return EXIT_OK


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main(sys.argv[1:]))
