"""refresh-gov-block.py -- keep every copy of the governance segment identical.

CANONICAL SOURCE
    preset/allin/allin.patch.yml -- the `<!-- GOVERNANCE:BEGIN` ... `<!-- GOVERNANCE:END`
    segment (hereafter "the governance segment"). This is the only text a human edits.

DERIVED COPIES
    1. preset/allin/agent.cordis.yml -- archived 0.1.6 directory-form preset (6-space
       indent, CRLF). Nothing loads it, which is how it ran a 2026-09 snapshot for a
       month without anyone noticing.
    2. <DSH_HOME>/profiles/web/cordis.patch.yml -- the *mounted* profile layer (16-space
       indent). This one reaches live sessions; on 2026-10-29 it was still telling new
       agents "15 gates" while the repository said 19.
    3. preset/allin/bundle/cordis.patch.yml -- the npm bundle copy. It is a whole-file
       copy regenerated by `make-bundle.ps1`, so this tool only *checks* it (one writer
       per file).
    4. .workbuddy/skills/allin-governance-agent/SKILL.md -- the WorkBuddy skill, i.e.
       the same governance facts as read by a WorkBuddy agent. Unlike copies 1-3 it is
       **not** a byte copy: a skill document is read by a human and by an agent, so the
       same facts have to arrive as readable Markdown, not as YAML-nested prose.
       `--targets workbuddy` therefore *renders* its marked segment from the canonical
       facts (see WORKBUDDY PROJECTION below) instead of re-indenting it.

WHY A TOOL
    Three copies plus hand edits is drift no gate inside the repository can see: copy 2
    lives outside the repo entirely. Prose cannot keep them in step; an idempotent writer
    can, and `--check` turns "is the deployment current?" into an exit code.

    Copy 4 was the last hold-out: SKILL.md carried the governance facts *by hand*, and
    the only thing tying it to the canonical segment was a comment telling humans and
    agents to "keep both sides in sync" -- a rule with no judge. 2026-11-25 the two sides
    were merged into one writer: the DSH segment stays the single hand-edited source and
    SKILL.md's governed surface becomes a rendering of it.

WORKBUDDY PROJECTION (--targets workbuddy)
    Copies 1-3 are the same bytes at another indent, so re-indenting them is enough.
    SKILL.md cannot be that, so the merge is over *facts*, not bytes. The tool extracts a
    declared fact subset from the canonical segment, renders it as a Markdown table, and
    owns the marked segment in SKILL.md:

      * render  -- a pure function of the canonical text. The table holds no content of
                   its own, so `--write` is idempotent by construction and a second run
                   is a byte-for-byte no-op;
      * check   -- compare the rendered table against the segment on disk *after
                   normalisation*: strip trailing whitespace per line, drop leading and
                   trailing blank lines, LF newlines. Column padding and indentation are
                   therefore free to differ; a changed **value** is not. A rewording that
                   keeps the value is green, a reworded value is red -- which is the point;
      * extract -- fail-loud. If the canonical prose stops yielding a declared fact (say
                   "共 N 道" disappears), that is a usage error, never an empty value: a
                   projection that silently drops a fact is worse than no projection.

    One fact cannot be rendered, because SKILL.md also quotes it in hand-written prose
    (the skill description says "跑 20 道治理门禁"). Prose is not machine-owned, so the
    tool only *judges* it: every `N 道门禁` outside the marked segment must equal the
    rendered N. This half is what stops prose from contradicting the table.

    THE 「」 CITATION EXEMPTION, AND WHY IT IS ANCHORED
    The 2026-10-29 incident is quoted on both sides as "仍写「15 道门禁」", and a post-mortem
    must be allowed to quote the wrong number verbatim -- evidence loses its value if it
    has to be paraphrased. So a quoted number is exempt. But quote marks alone are free to
    type: exempting on 「」 alone means "wrap the claim in brackets and it is immune", which
    is a hole, not an exemption. The exemption is therefore anchored to a **date**: the
    quoted number is treated as a citation only when a `YYYY-MM-DD` appears within
    ``QUOTE_WINDOW`` characters before the opening bracket.

    The window walks back to the start of the *paragraph*, not of the line, because
    Markdown soft-wraps: SKILL.md:236 carries "2026-10-29 实测…落后了整整一代" and :237
    carries "（仍写「15 道门禁」）". A line-scoped window would flag exactly the line this
    exemption exists to protect. It never leaves the paragraph -- a date in the previous
    block is a citation of something else.

    RESIDUAL RISK, stated rather than hidden: a date is still cheap to type, so someone
    determined to dodge the check can write a false one. That is the intended trade -- it
    moves the cost of dodging from "add two characters" to "assert a fabricated fact",
    which is a reviewable act rather than an accident. No lexical rule makes this
    undodgeable; anchors only make dodging deliberate.

USAGE
    python preset/allin/refresh-gov-block.py --check
    python preset/allin/refresh-gov-block.py --write
    python preset/allin/refresh-gov-block.py --write --targets agent
    python preset/allin/refresh-gov-block.py --check --targets workbuddy
    python preset/allin/refresh-gov-block.py --check --profile-path <path>

EXIT CODES
    0  every copy is fresh (or was just refreshed)
    2  usage error, the canonical governance segment is not a well-formed pair, or the
       canonical text no longer yields a declared WorkBuddy fact (extraction is fail-loud)
    3  at least one derived copy is stale (mirrors `make-bundle.ps1 -Check`); in --check
       mode, or when hand-written SKILL.md prose contradicts the rendered fact subset --
       that half cannot be auto-fixed, so --write returns 3 as well instead of papering
       over it
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

CANONICAL = Path("preset") / "allin" / "allin.patch.yml"
AGENT_COPY = Path("preset") / "allin" / "agent.cordis.yml"
BUNDLE_COPY = Path("preset") / "allin" / "bundle" / "cordis.patch.yml"
PROFILE_COPY = Path("profiles") / "web" / "cordis.patch.yml"
WORKBUDDY_COPY = Path(".workbuddy") / "skills" / "allin-governance-agent" / "SKILL.md"
WORKBUDDY_TARGETS = ("agent", "profile", "bundle", "workbuddy")

MARKER_BEGIN = "<!-- GOVERNANCE:BEGIN"
MARKER_END = "<!-- GOVERNANCE:END"

EXIT_OK = 0
EXIT_USAGE = 2
EXIT_STALE = 3


@dataclass
class Reading:
    """One file as it is on disk, plus the two conventions a rewrite must preserve."""

    text: str
    bom: bool
    eol: str


def read(path: Path) -> Reading:
    """Read UTF-8 text and remember whether it carried a BOM and which EOL it used."""
    raw = path.read_bytes()
    bom = raw.startswith(b"\xef\xbb\xbf")
    text = raw.decode("utf-8-sig")
    eol = "\r\n" if "\r\n" in text else "\n"
    return Reading(text=text, bom=bom, eol=eol)


def write(path: Path, reading: Reading, text: str) -> None:
    """Write back with the original BOM and EOL convention: no incidental diff noise."""
    body = text.replace("\r\n", "\n").replace("\n", reading.eol)
    path.write_bytes((b"\xef\xbb\xbf" if reading.bom else b"") + body.encode("utf-8"))


def marker_indexes(lines: list[str]) -> tuple[int, int] | None:
    """Line indexes of the marked segment, anchored on the marker *lines*.

    A prose comment above a preset legitimately names the markers ("GOVERNANCE:BEGIN/END
    段"), so a substring search would return the comment block instead of the segment.
    """
    starts = [i for i, line in enumerate(lines) if line.strip().startswith(MARKER_BEGIN)]
    stops = [i for i, line in enumerate(lines) if line.strip().startswith(MARKER_END)]
    if len(starts) != 1 or len(stops) != 1 or stops[0] < starts[0]:
        return None
    return starts[0], stops[0]


def normalize(lines: list[str]) -> str:
    """Comparable form: no common indent, no trailing blanks, LF newlines."""
    trimmed = [line.rstrip() for line in lines]
    indents = [len(line) - len(line.lstrip()) for line in trimmed if line.strip()]
    base = min(indents) if indents else 0
    return "\n".join(line[base:] if line.strip() else "" for line in trimmed).strip("\n")


def reindent(lines: list[str], indent: int) -> list[str]:
    return [(" " * indent + line) if line.strip() else "" for line in normalize(lines).split("\n")]


def detect_indent(lines: list[str]) -> int:
    indents = [len(line) - len(line.lstrip()) for line in lines if line.strip()]
    return min(indents) if indents else 0


def default_profile() -> Path | None:
    """The mounted profile layer for this machine, or None when there is none."""
    home = os.environ.get("DSH_HOME")
    base = Path(home) if home else Path.home() / ".dsh"
    candidate = base / PROFILE_COPY
    return candidate if candidate.is_file() else None


def first_difference(current: str, canonical: str) -> str:
    """A one-line pointer to where a stale copy diverges: usable, not just "different"."""
    left = current.split("\n")
    right = canonical.split("\n")
    for number, (a, b) in enumerate(zip(left, right), start=1):
        if a != b:
            column = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
            low = max(0, column - 16)
            return (f"first difference at segment line {number}, column {column + 1}: "
                    f"{a[low:column + 20]!r} != {b[low:column + 20]!r}")
    return f"line count {len(left)} != canonical {len(right)}"


def refresh_segment(path: Path, canonical_lines: list[str]) -> tuple[int, int]:
    """Rewrite the marked segment in ``path`` from the canonical text; return (old, new) lines."""
    reading = read(path)
    lines = reading.text.splitlines()
    indexes = marker_indexes(lines)
    if indexes is None:
        raise SystemExit(f"{path}: {MARKER_BEGIN}/{MARKER_END} is not a well-formed pair")
    start, stop = indexes
    new_lines = reindent(canonical_lines, detect_indent(lines[start : stop + 1]))
    rebuilt = "\n".join(lines[:start] + new_lines + lines[stop + 1 :])
    write(path, reading, rebuilt + reading.eol)
    return stop - start + 1, len(new_lines)


# --------------------------------------------------------------------------- #
# WorkBuddy projection: declared facts out of the canonical segment, Markdown back in
# --------------------------------------------------------------------------- #

class Usage(Exception):
    """The canonical text stops yielding a declared fact: refuse to render a guess."""


@dataclass(frozen=True)
class Fact:
    """One governance fact, rendered as one Markdown table row."""

    key: str
    label: str
    value: str


#: Declared command entry points. This is a *selector*, not a second source of truth:
#: only the ones the canonical segment actually names are rendered, and extraction
#: fails loudly if none survive.
GATE_COMMANDS = (
    "bash scripts/run_all_gates.sh",
    "npm run check:governance",
    "docs_index.py",
    "tools/gate/agent_regression.py",
    "python preset/allin/refresh-gov-block.py --check",
)

ROOT_SECTION = "定位仓根（命中即用，按序）"
READING_SECTION = "四份（位于"
READING_SECTION_END = "需要背景时"
GATE_CLAIM = re.compile(r"(\d+)\s*道(?:治理)?门禁")
#: How far in front of a quoted number we look for the date that makes it a citation.
#: 60 characters covers "：2026-10-29 实测挂载层落后了整整一代\n（仍写「" with room to spare.
QUOTE_WINDOW = 60
CITATION_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
DERIVED_PATHS = re.compile(r"`([^`]*(?:agent\.cordis\.yml|bundle/cordis\.patch\.yml|cordis\.patch\.yml)[^`]*)`")


def section(text: str, start: str, stop: str) -> list[str]:
    """The lines from the one containing ``start`` up to (not including) ``stop``."""
    lines = text.split("\n")
    first = next((i for i, line in enumerate(lines) if start in line), None)
    if first is None:
        raise Usage(f"规范段里找不到小节「{start}」（本工具的定位锚点）")
    last = next((i for i in range(first + 1, len(lines)) if stop in lines[i]), len(lines))
    return lines[first:last]


def gate_count(norm: str) -> str:
    """The governance gate count as the canonical segment states it ("共 N 道")."""
    found = re.findall(r"共\s*(\d+)\s*道", norm)
    if not found:
        raise Usage(
            "规范段里找不到「共 N 道」（门禁道数的唯一写法）。道数是双端最容易漂移的一条事实"
            "（2026-10-29 挂载层还写着「15 道」，仓内已是 20），所以提取失败即报错，不猜")
    return found[0]


def workbuddy_facts(norm: str) -> list[Fact]:
    """The declared fact subset: what both harnesses must state identically.

    Selection rule -- a fact earns a row when it is (a) a *value* an agent acts on (a
    repo name, a path, a count, a command), (b) expensive to get wrong, and (c) already
    stated in the canonical segment. Narrative, persona framing, YAML shape and
    harness-specific tool-call details stay out: they are not facts, and copying them
    would turn a skill document into a preset excerpt.
    """
    def pick(pattern: str, what: str, count: int | None = None) -> list[str]:
        found = re.findall(pattern, norm, re.MULTILINE)
        if not found or (count is not None and len(found) != count):
            wanted = f"恰好 {count} 项" if count is not None else "至少 1 项"
            raise Usage(
                f"规范段的{what}解析不出{wanted}（正则 {pattern!r} 命中 {len(found)} 项）。"
                f"本工具不从猜测取数：改 {CANONICAL.as_posix()} 治理段时请保留该写法，"
                f"或同步更新 preset/allin/refresh-gov-block.py 的提取式")
        return found

    repo = pick(r"工作区治理仓是\s*`([^`]+)`", "治理仓名", 1)[0]
    former = pick(r"前目录名为\s*`([^`]+)`", "治理仓原名", 1)[0]
    if "禁止硬编码盘符" not in norm:
        raise Usage("规范段里找不到「禁止硬编码盘符」（SPEC-001 铁律 5 的载体）；"
                    "这条禁令是双端必须同时为真的事实，缺了就不渲染")

    steps: list[str] = []
    for line in section(norm, ROOT_SECTION, READING_SECTION):
        if not re.match(r"\s*\d\.\s", line):
            continue
        spans = [span for span in re.findall(r"`([^`]+)`", line) if "{{" not in span]
        if spans:
            steps.append(spans[0])
    if len(steps) != 4:
        raise Usage(f"规范段的定位仓根步骤解析出 {len(steps)} 步（应为 4 步且各带一个代码跨度）")

    hubs = list(dict.fromkeys(re.findall(
        r"`<仓根>/(docs/[^`]+)`", "\n".join(section(norm, READING_SECTION, READING_SECTION_END)))))
    if len(hubs) != 4:
        raise Usage(f"规范段的「开卷必读四份」解析出 {len(hubs)} 份（应为 4 份）")

    laws = pick(r"^([0-2])\. \*\*(.+?)\*\*", "三条铁律编号与标题", 3)
    numbers = [number for number, _title in laws]
    titles = [title for _number, title in laws]
    specs = sorted(set(pick(r"SPEC-\d{3}", "规范编号")))

    ids = pick(r"g\d\d-[a-z][a-z-]*", "门禁 id")
    highest = max(int(identifier[1:3]) for identifier in ids)
    gates = gate_count(norm)
    first_gate = min(ids)
    last_gate = next(identifier for identifier in ids if int(identifier[1:3]) == highest)

    commands = [command for command in GATE_COMMANDS if command in norm]
    if not commands:
        raise Usage(f"规范段里找不到任何已声明的命令入口（候选取自 {GATE_COMMANDS}）")

    copies = list(dict.fromkeys(DERIVED_PATHS.findall(norm)))
    if not copies:
        raise Usage("规范段的「派生副本」解析不出任何路径（agent.cordis.yml / bundle / 挂载层）")

    def joined(items: list[str]) -> str:
        """Backtick-join code spans into one table cell."""
        return " · ".join(f"`{item}`" for item in items)

    return [
        Fact("repo", "治理仓",
             f"`{repo}`（2026-09-27 前名 `{former}`）；**禁止硬编码盘符**（SPEC-001 铁律 5）"),
        Fact("root", "定位仓根（命中即用，按序）",
             f"{len(steps)} 步：" + " → ".join(f"`{step}`" for step in steps)),
        Fact("reading", "开卷必读四份（`<仓根>/` 下）", "、".join(f"`{hub}`" for hub in hubs)),
        Fact("rules", "铁律与规范编号",
             f"铁律 {'/'.join(numbers)}（{' / '.join(titles)}）；规范编号 {' · '.join(specs)}"),
        Fact("gates", "治理门禁与入口",
             f"共 {gates} 道治理门禁（`{first_gate}` … `{last_gate}`）；入口 {joined(commands)}"),
        Fact("copies", "派生副本（单写者）",
             f"1 份正文 + {len(copies)} 份派生副本（{joined(copies)}）；"
             f"副本与本段同由 `python preset/allin/refresh-gov-block.py` 渲染，"
             f"bundle 另跑 `make-bundle.ps1`"),
    ]


def render_workbuddy(norm: str) -> str:
    """Render SKILL.md's governed segment. A pure function of the canonical text.

    Nothing in here is authored twice: every cell comes from ``workbuddy_facts``, so a
    second ``--write`` cannot change a byte and ``--check`` compares like with like.
    """
    facts = workbuddy_facts(norm)
    head = (f"{MARKER_BEGIN} -->**治理事实投影（WorkBuddy 侧）** · 本段由 "
            f"`python preset/allin/refresh-gov-block.py --targets workbuddy` 从 "
            f"`preset/allin/allin.patch.yml` 的 `GOVERNANCE` 段渲染 —— **本段禁止手改**："
            f"改规范段后重跑 `--write`，`--check` 判漂移（落后 exit 3，已并入 "
            f"`npm run check:preset-sync`）。")
    note = ("下表是双端**必须同源**的事实子集：措辞可不同，取值只有一个来源（规范段）。"
            "表外内容不进本投影 —— DSH persona 前缀与 YAML 缩进是形态差异，"
            "路由表锚点由 `tools/gate/agent_parity.py` 三方对账，"
            "ReAct / 记忆回路的操作细节由下文各节展开。")
    body = ["| 事实 | 取值（自规范段渲染） |", "| --- | --- |"]
    body += [f"| {fact.label} | {fact.value} |" for fact in facts]
    return "\n".join([head, "", note, "", *body, f"{MARKER_END} -->"])


def window_before(lines: list[str], index: int, column: int) -> str:
    """Up to ``QUOTE_WINDOW`` characters before ``column`` on line ``index``.

    Walks back to the start of the *paragraph* rather than stopping at the line start,
    because a soft-wrapped paragraph splits a citation from its date (SKILL.md:236 has
    the date, :237 has the quote). It stops at a blank line: a date in another block
    cites something else and must not lend authority to this number.
    """
    text = lines[index][:column]
    cursor = index
    while len(text) < QUOTE_WINDOW and cursor > 0 and lines[cursor - 1].strip():
        cursor -= 1
        text = lines[cursor] + text
    return text[-QUOTE_WINDOW:]


def prose_drift(lines: list[str], expected: str, skip: tuple[int, int]) -> list[str]:
    """Hand-written prose must not contradict the rendered gate count.

    ``skip`` is the marked segment (0-based, inclusive) -- that half is machine-owned and
    already compared byte-wise, so judging it twice would report one defect twice.

    A quoted number is exempt only when it reads as a citation: a date must sit within
    ``QUOTE_WINDOW`` characters before the opening bracket. Quote marks alone are not a
    licence -- anyone can type them around a claim, and an exemption that free to obtain
    is a hole. See the module docstring for the residual risk we accept knowingly.
    """
    problems: list[str] = []
    for index, line in enumerate(lines):
        if skip[0] <= index <= skip[1]:
            continue
        for match in GATE_CLAIM.finditer(line):
            if match.group(1) == expected:
                continue
            start, end = match.span()
            quoted = start > 0 and line[start - 1] == "「" and end < len(line) and line[end] == "」"
            if quoted and CITATION_DATE.search(window_before(lines, index, start - 1)):
                continue
            rule = (f"（引号内的数字须在引号前 {QUOTE_WINDOW} 字符内出现 YYYY-MM-DD 才算历史引述）"
                    if quoted else "")
            problems.append(
                f"{WORKBUDDY_COPY.as_posix()}:{index + 1} 写的是「{match.group(0)}」，"
                f"规范段渲染值为「{expected} 道治理门禁」；散文不得与投影表打架 —— "
                f"请手改这一行（散文不由 --write 代笔）{rule}")
    return problems



def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(
        description="keep every governance-segment copy identical to preset/allin/allin.patch.yml")
    parser.add_argument("--check", action="store_true", help="compare only; exit 3 when a copy is stale")
    parser.add_argument("--write", action="store_true",
                        help="rewrite the stale copies (agent, profile, workbuddy)")
    parser.add_argument("--targets", default=",".join(WORKBUDDY_TARGETS),
                        help="comma list drawn from agent,profile,bundle,workbuddy (default: all four)")
    parser.add_argument("--profile-path", default="",
                        help="mounted profile patch (default: $DSH_HOME/profiles/web/cordis.patch.yml)")
    args = parser.parse_args(argv)
    if args.check == args.write:
        print("pass exactly one of --check / --write")
        return EXIT_USAGE

    repo = Path(__file__).resolve().parents[2]
    canonical_path = repo / CANONICAL
    if not canonical_path.is_file():
        print(f"canonical source missing: {canonical_path}")
        return EXIT_USAGE
    canonical_lines = read(canonical_path).text.splitlines()
    canonical_indexes = marker_indexes(canonical_lines)
    if canonical_indexes is None:
        print(f"{canonical_path}: {MARKER_BEGIN}/{MARKER_END} is not a well-formed pair")
        return EXIT_USAGE
    canonical_slice = canonical_lines[canonical_indexes[0] : canonical_indexes[1] + 1]
    canonical_norm = normalize(canonical_slice)
    print(f"canonical: {len(canonical_slice)} lines / {len(canonical_norm)} chars "
          f"from {CANONICAL.as_posix()}")

    wanted = [item.strip() for item in args.targets.split(",") if item.strip()]
    unknown = [item for item in wanted if item not in WORKBUDDY_TARGETS]
    if unknown:
        print(f"unknown target(s): {', '.join(unknown)}")
        return EXIT_USAGE

    stale: list[str] = []
    unjudged: list[str] = []
    for target in wanted:
        if target == "bundle":
            bundle_path = repo / BUNDLE_COPY
            if not bundle_path.is_file():
                print("bundle : missing -> run make-bundle.ps1")
                stale.append("bundle")
            elif hashlib.sha256(canonical_path.read_bytes()).hexdigest() == \
                    hashlib.sha256(bundle_path.read_bytes()).hexdigest():
                print("bundle : fresh (byte-identical to the canonical patch)")
            else:
                print("bundle : STALE -> run make-bundle.ps1 (whole-file copy, not written by this tool)")
                stale.append("bundle")
            continue

        if target == "workbuddy":
            path = repo / WORKBUDDY_COPY
            if not path.is_file():
                print(f"workbuddy: missing -> {WORKBUDDY_COPY.as_posix()}")
                stale.append("workbuddy")
                continue
            try:
                expected = render_workbuddy(canonical_norm)
                expected_gates = gate_count(canonical_norm)
            except Usage as exc:
                print(f"workbuddy: cannot render -- {exc}")
                return EXIT_USAGE
            reading = read(path)
            lines = reading.text.splitlines()
            indexes = marker_indexes(lines)
            if indexes is None:
                print(f"workbuddy: {MARKER_BEGIN} -->/{MARKER_END} --> is not a well-formed pair "
                      f"in {WORKBUDDY_COPY.as_posix()}; insert the pair once, then --write")
                stale.append("workbuddy")
                continue
            start, stop = indexes
            current = normalize(lines[start : stop + 1])
            wanted_block = normalize(expected.split("\n"))
            if current == wanted_block:
                print(f"workbuddy: fresh {stop - start + 1} lines / {len(current)} chars")
            elif not args.write:
                print(f"workbuddy: STALE ({first_difference(current, wanted_block)}) -> {path}")
                stale.append("workbuddy")
            else:
                new_lines = expected.split("\n")
                rebuilt = "\n".join(lines[:start] + new_lines + lines[stop + 1 :])
                write(path, reading, rebuilt + reading.eol)
                print(f"workbuddy: refreshed ({stop - start + 1} -> {len(new_lines)} lines) -> {path}")
            for problem in prose_drift(lines, expected_gates, (start, stop)):
                print(f"workbuddy: PROSE CONTRADICTS SOURCE -- {problem}")
                unjudged.append("workbuddy")
            continue

        if target == "agent":
            path = repo / AGENT_COPY
        else:
            path = Path(args.profile_path) if args.profile_path else default_profile()
            if path is None:
                print("profile: no mounted profile layer on this machine -- skipped (not a pass)")
                continue
            if not path.is_file():
                print(f"profile: {path} does not exist -- skipped (not a pass)")
                continue

        reading = read(path)
        indexes = marker_indexes(reading.text.splitlines())
        if indexes is None:
            print(f"{target}: {MARKER_BEGIN}/{MARKER_END} is not a well-formed pair; cannot judge")
            stale.append(target)
            continue
        current = normalize(reading.text.splitlines()[indexes[0] : indexes[1] + 1])
        if current == canonical_norm:
            print(f"{target}: fresh {indexes[1] - indexes[0] + 1} lines / {len(current)} chars")
            continue
        if not args.write:
            print(f"{target}: STALE ({first_difference(current, canonical_norm)}) -> {path}")
            stale.append(target)
            continue
        old_count, new_count = refresh_segment(path, canonical_slice)
        print(f"{target}: refreshed ({old_count} -> {new_count} lines) -> {path}")

    if args.check and stale:
        print(f"stale copy/copies: {', '.join(stale)}")
        return EXIT_STALE
    if unjudged:
        print(f"hand-written prose contradicts the source: {', '.join(sorted(set(unjudged)))} "
              f"(not auto-fixable -- edit the named line, then re-run)")
        return EXIT_STALE
    return EXIT_OK


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main(sys.argv[1:]))
